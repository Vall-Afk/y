function normalizeLanguage(language) { return language === 'en' ? 'en' : 'id'; }
function tr(language, key, args = {}) {
  let message = MESSAGES[normalizeLanguage(language)][key] ||
    MESSAGES.id[key] || key;
  for (const [name, value] of Object.entries(args)) {
    message = message.replaceAll('{' + name + '}', String(value));
  }
  return message;
}
